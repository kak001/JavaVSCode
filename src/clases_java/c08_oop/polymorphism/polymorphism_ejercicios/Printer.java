package clases_java.c08_oop.polymorphism.polymorphism_ejercicios;

public class Printer {
    // Metodos
    public String print(String name) {
        return name;
    }

    public int print(int age) {
        return age;
    }

    public double print(double height) {
        return height;
    }

    public char print(char initial) {
        return initial;
    }

    public boolean print(boolean trueOrFalse) {
        return trueOrFalse;
    }
}
